"""Generate paper/numbers.tex: every number cited in the paper is a macro defined here from results CSVs / data files."""
import pandas as pd, re, json, os
W = {}
def name(*parts): return ''.join(re.sub(r'[^A-Za-z]', '', p.replace('@5', 'Five').replace('@10', 'Ten').replace('2.1', 'Two').replace('v21', 'Two')).title() for p in parts)
def put(k, v, fmt='{:.3f}'): W[k] = fmt.format(v) if isinstance(v, float) else (f'{v:,}' if isinstance(v, int) else str(v))
# data counts
h = json.load(open('data/hpd_tattoo.json')); put('nHPDpairsAll', len(h)); put('nHPDpromptsAll', len({x['prompt'] for x in h}))
put('nHPDimgs', len(pd.read_csv('data/manifest_hpd.csv'))); put('nIRimgs', len(pd.read_csv('data/manifest_ir.csv'))); put('nIRrows', len(pd.read_csv('data/ir_tattoo.csv')))
put('nIRempty', len(pd.read_csv('data/ir_tattoo.csv')) - len(pd.read_csv('data/manifest_ir.csv')))
pp = pd.read_csv('data/pap_tattoo_pairs.csv'); lab = pp[pp.has_label.astype(bool) & pp.are_different.astype(bool)]
put('nPAProws', len(pp)); put('nPAPpairs', len(lab)); put('nPAPprompts', pp.caption.nunique())
for ds in ['hpd', 'ir']:
    c = pd.read_csv(f'data/cls_{ds}.csv')
    for k, v in c.cls.value_counts().items(): put(name('n', ds, 'cls', k), int(v))
    for k, v in c.cls_v2.value_counts().items(): put(name('n', ds, 'clsTwo', k), int(v))
a = pd.read_csv('data/ambiguous_review.csv'); put('nAmb', len(a))
for k, v in a.manual.value_counts().items(): put(name('nAmb', k), int(v))
d = pd.read_csv('data/manifest_degr.csv'); put('nDegrDesigns', d.src.nunique()); put('nDegrImgs', len(d)); put('nDegrRewDesigns', pd.read_csv('data/manifest_degr60.csv').src.nunique())
# per-dimension
for r in pd.read_csv('results/per_dimension.csv').itertuples():
    b = name(r.dataset, r.scorer); put(b + 'Acc', r.acc); put(b + 'Lo', r.ci_lo); put(b + 'Hi', r.ci_hi); put(b + 'N', int(r.n_pairs))
    put(name('n', r.dataset, 'tsPrompts'), int(r.n_prompts))
    put(b + 'Effect', r.effect, '{:+.3f}'); put(b + 'H', r.cohens_h, '{:+.2f}'); put(b + 'Pholm', r.p_holm, '{:.3f}')
D = pd.read_csv('results/per_dimension.csv')
for ds, g in D.groupby('dataset'): put(name('n', ds, 'SigHolm'), int(g.sig_holm_05.sum())); put(name('n', ds, 'Tests'), len(g))
for r in pd.read_csv('results/fusion_lopo.csv').itertuples():
    b = name('fus', r.dataset, r.model); put(b + 'Acc', r.acc); put(b + 'Lo', r.ci_lo); put(b + 'Hi', r.ci_hi); put(b + 'N', int(r.n_pairs))
# degradation
r = pd.read_csv('results/degr_detection_withrewards.csv')
for x in r.itertuples(): put(name('dg', x.scorer, x.op, ['', 'One', 'Two'][x.level]), x.acc, '{:.2f}')
# scale/spread
s = pd.read_csv('results/scale_spread.csv'); s0 = s[s.noise == 0] if 'noise' in s else s
for (sz, sp), g in s0.groupby(['size_cm', 'spread_mm']):
    SW={3:'Three',5:'Five',10:'Ten',15:'Fifteen'}; PW=dict(zip(range(0,65,5),'Zero Five Ten Fifteen Twenty TwentyFive Thirty ThirtyFive Forty FortyFive Fifty FiftyFive Sixty'.split())); tag = 'Size'+SW[int(sz)]+'Spread'+PW[int(round(sp*100))]
    put('ssFone' + tag, g.skel_f1.mean()); put('ssGap' + tag, g.gap_survival.mean())
if 'noise' in s:
    for sz, g in s[(s.noise > 0) & (s.spread_mm == 0)].groupby('size_cm'): put('ssNoiseFoneS' + 'iii thf iof iff'.split()[[3,5,10,15].index(int(sz))] if False else f"ssNoiseFone{['Three','Five','Ten','Fifteen'][[3,5,10,15].index(int(sz))]}", g.skel_f1.mean())
c = pd.read_csv('results/scale_spread_predict.csv')
for x in c[c.size_cm == 5].itertuples(): put(name('rho', x.probe.replace('probe_', ''), x.target), x.rho, '{:.3f}')
PW=dict(zip(range(0,65,5),'Zero Five Ten Fifteen Twenty TwentyFive Thirty ThirtyFive Forty FortyFive Fifty FiftyFive Sixty'.split()))
for x in pd.read_csv('results/spread_sensitivity.csv').itertuples():
    put('minSize' + ('Seventy' if x.threshold == 0.7 else 'Eighty') + 'Spread' + PW[int(round(x.spread_mm * 100))], 'n/a' if pd.isna(x.min_size_cm) else f'{x.min_size_cm:g}')
if os.path.exists('data/pairs_pap_all.csv'):
    pa = pd.read_csv('data/pairs_pap_all.csv'); put('nPAPkwPairs', len(pa)); put('nPAPkwPrompts', pa.prompt.nunique()); put('nPAPimgs', len(pd.read_csv('data/manifest_pap.csv')))
    c = pd.read_csv('data/cls_pap.csv')
    for k, v in c.cls.value_counts().items(): put(name('n', 'pap', 'cls', k), int(v))
os.makedirs('../paper', exist_ok=True)
open('../paper/numbers.tex', 'w').write('% AUTO-GENERATED by tattoo-probes/scripts/make_numbers.py -- do not edit\n' + ''.join(f'\\newcommand{{\\{k}}}{{{v}}}\n' for k, v in sorted(W.items())))
json.dump(W, open('../paper/numbers.json', 'w'), indent=0); print(len(W))
